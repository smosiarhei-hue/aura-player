        didPrepare = true
        guard let data = Data(base64Encoded: fontBase64, options: .ignoreUnknownCharacters),
              let provider = CGDataProvider(data: data as CFData),
              let font = CGFont(provider),
              let name = font.postScriptName else { return nil }
        guard CTFontManagerRegisterGraphicsFont(font, nil) else { return nil }
        registeredName = name as String
        return registeredName
